#!/usr/bin/env node
/**
 * Install or refresh the `dsh-cli` DSH profile.
 *
 * Why a derived profile exists at all:
 *
 * - The stock `sdk` profile serves JSON-RPC but carries no Desktop capability
 *   rows, so a terminal session only sees the built-in DeepSeek route.
 * - The `desktop` profile has every capability row but cannot be booted from a
 *   terminal: the DSH launcher rejects it with
 *   `error: profile "desktop" is managed exclusively by the Electron application`.
 *
 * `dsh-cli` is therefore `dsh-base` + `dsh-sdk-app` (the JSON-RPC server) with
 * the capability rows copied verbatim from the Desktop profile patch: default
 * route, providers/models, web search + fetch, permissions, subagents.
 *
 * The copy is one-way and read-only towards Desktop: this script never edits
 * the Desktop profile, never touches credentials, and only reads
 * `profiles/desktop/cordis.patch.yml`.
 *
 * Usage:
 *   node scripts/install-profile.mjs [--dry-run] [--home <dir>] [--source <patch>]
 *
 * @module scripts/install-profile
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

/** Profile directory name the CLI boots by default. */
export const CLI_PROFILE = 'dsh-cli';

/**
 * Capability rows copied from the Desktop profile patch, in copy order.
 *
 * Deliberately excluded: Electron/UI rows (`desktop-shell`, `ui-*`), AgentTeams
 * rows, and the plugin-market bundles — a terminal client has no renderer, and
 * those rows pull in the very Electron surface this CLI exists to avoid.
 */
export const COPIED_ROWS = Object.freeze([
  'agent-default-model',
  'subagent',
  'web',
  'permission',
  'llm-pi-ai',
  'llm-deepseek',
  'web-deepseek-api',
]);

/** Bundles the CLI profile mounts: the shared core plus the JSON-RPC server. */
export const PROFILE_BUNDLES = Object.freeze([
  '@deepseek-ai/dsh-base',
  '@deepseek-ai/dsh-sdk-app',
]);

const ROW_START = /^- /;
const ROW_ID = /^- id:\s*(\S+)\s*$/;

/**
 * Split a Cordis patch list into its top-level rows.
 *
 * The patch dialect is a YAML array whose entries start at column 0 with `- `,
 * so row boundaries are unambiguous without parsing YAML.
 *
 * @param {string} text Patch file contents.
 * @returns {{ id: string, lines: string[] }[]} Rows in file order.
 */
export function splitPatchRows(text) {
  /** @type {{ id: string, lines: string[] }[]} */
  const rows = [];
  /** @type {{ id: string, lines: string[] } | null} */
  let current = null;
  for (const line of String(text).split(/\r?\n/)) {
    if (ROW_START.test(line)) {
      const match = ROW_ID.exec(line);
      current = { id: match === null ? '' : match[1], lines: [line] };
      rows.push(current);
      continue;
    }
    if (current !== null) current.lines.push(line);
  }
  return rows;
}

/**
 * Build the CLI profile patch from the Desktop profile patch.
 *
 * @param {string} desktopPatch Desktop `cordis.patch.yml` contents.
 * @param {readonly string[]} [wanted] Row ids to copy.
 * @param {{ provider?: string, model?: string }} [route] Override the copied
 *   default route. The Desktop route is copied verbatim, which is wrong when the
 *   Desktop default is rate-limited or its credential expired.
 * @returns {{ text: string, copied: string[], missing: string[] }} Patch text plus
 *   which rows were found and which were absent.
 */
export function buildProfilePatch(desktopPatch, wanted = COPIED_ROWS, route = {}) {
  const byId = new Map(
    splitPatchRows(desktopPatch)
      .filter((row) => row.id !== '')
      .map((row) => [row.id, row]),
  );
  /** @type {string[]} */
  const lines = [
    '# Generated by dsh-cli/scripts/install-profile.mjs — do not edit by hand.',
    '#',
    '# Capability rows copied from the Desktop profile so a terminal session sees',
    '# the same models, providers, permissions and web providers as the GUI,',
    '# without booting Electron. Refresh with:',
    '#   node scripts/install-profile.mjs',
  ];
  /** @type {string[]} */
  const copied = [];
  /** @type {string[]} */
  const missing = [];
  for (const id of wanted) {
    const row = byId.get(id);
    if (row === undefined) {
      missing.push(id);
      continue;
    }
    copied.push(id);
    lines.push('', `# == ${id} (copied from the Desktop profile)`);
    const body = [...row.lines];
    while (body.length > 0 && body[body.length - 1].trim() === '') body.pop();
    lines.push(...(id === 'agent-default-model' ? applyRouteOverride(body, route) : body));
  }
  return { text: `${lines.join('\n')}\n`, copied, missing };
}

/**
 * Replace `provider:`/`model:` inside the copied default-route row.
 *
 * Rewriting the row (rather than appending a second one) keeps exactly one
 * `agent-default-model` entry, so the loader cannot see two conflicting routes.
 * A pinned route also drops `reasoningEffort`, because Desktop's effort is
 * model-specific and a different model may reject it outright.
 *
 * @param {string[]} body `agent-default-model` row lines.
 * @param {{ provider?: string, model?: string }} route Overrides.
 * @returns {string[]} Row with the requested route.
 */
function applyRouteOverride(body, route) {
  if (route.provider === undefined && route.model === undefined) return body;
  /** @type {string[]} */
  const out = [];
  for (const line of body) {
    const keyed = /^(\s*)(provider|model|reasoningEffort|maxTokens)\s*:\s*(.+?)\s*$/.exec(line);
    if (keyed === null) {
      out.push(line);
      continue;
    }
    const [, indent, key] = keyed;
    if (key === 'reasoningEffort' || key === 'maxTokens') continue;
    const value = key === 'provider' ? route.provider : route.model;
    out.push(value === undefined ? line : `${indent}${key}: ${value}`);
  }
  return out;
}

/**
 * The CLI profile manifest.
 *
 * @returns {string} `package.json` contents.
 */
export function buildProfileManifest() {
  const manifest = {
    name: 'dsh-profile-dsh-cli',
    private: true,
    dependencies: {},
    dsh: { profile: { bundles: [...PROFILE_BUNDLES] } },
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/**
 * Resolve the DSH home directory the runtime will use.
 *
 * @param {Record<string, string | undefined>} [env] Environment to read.
 * @returns {string} Absolute DSH home.
 */
export function resolveHome(env = process.env) {
  return env.DSH_HOME !== undefined && env.DSH_HOME !== ''
    ? env.DSH_HOME
    : path.join(os.homedir(), '.dsh');
}

/**
 * Parse this script's flags.
 *
 * @param {string[]} argv Arguments after the script path.
 * @param {Record<string, string | undefined>} [env] Environment for the default home.
 * @returns {{ home: string, source: string, dryRun: boolean, help: boolean }} Options.
 * @throws {Error} On an unknown flag or a missing flag value.
 */
export function parseOptions(argv, env = process.env) {
  const options = {
    home: resolveHome(env),
    source: '',
    dryRun: false,
    help: false,
    provider: undefined,
    model: undefined,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const token = argv[index];
    if (token === '--home' || token === '--source' || token === '--provider' || token === '--model') {
      const value = argv[index + 1];
      if (value === undefined || value === '') throw new Error(`${token} needs a value`);
      if (token === '--home') options.home = path.resolve(value);
      else if (token === '--source') options.source = path.resolve(value);
      else if (token === '--provider') options.provider = value;
      else options.model = value;
      index += 1;
    } else if (token === '--dry-run') {
      options.dryRun = true;
    } else if (token === '--help' || token === '-h') {
      options.help = true;
    } else {
      throw new Error(`unknown option: ${token}`);
    }
  }
  if (options.provider !== undefined && options.model === undefined) {
    throw new Error('--provider also needs --model');
  }
  if (options.source === '') {
    options.source = path.join(options.home, 'profiles', 'desktop', 'cordis.patch.yml');
  }
  return options;
}

const HELP = `Install or refresh the dsh-cli DSH profile.

Usage: node scripts/install-profile.mjs [--dry-run] [--home <dshHome>] [--source <patch>]
                                       [--provider <id> --model <id>]

Writes <dshHome>/profiles/dsh-cli:
  package.json      dsh-base + dsh-sdk-app bundles (the JSON-RPC server)
  cordis.patch.yml  capability rows copied from the Desktop profile patch

--provider/--model pin the copied default route instead of inheriting Desktop's,
which is what you want when Desktop's default is rate-limited or expired.

Read-only towards the Desktop profile. Never reads credentials.
`;

/**
 * Install the `dsh-cli` profile without printing a report.
 *
 * Split out of {@link main} so the top-level installer can compose it, and so a
 * caller can install a profile without capturing stdout.
 *
 * @param {{ env?: Record<string, string | undefined>, force?: boolean, source?: string, home?: string }} [options]
 * @returns {Promise<{ written: boolean, targetDir: string, copied: string[], missing: string[] }>}
 * @throws {Error} When the Desktop profile patch cannot be read.
 */
export async function installProfile(options = {}) {
  const env = options.env ?? process.env;
  const home = options.home ?? resolveHome(env);
  const source = options.source ?? path.join(home, 'profiles', 'desktop', 'cordis.patch.yml');
  if (!existsSync(source)) {
    throw new Error(`Desktop profile patch not found: ${source}`);
  }
  const built = buildProfilePatch(readFileSync(source, 'utf8'), COPIED_ROWS, {});
  const targetDir = path.join(home, 'profiles', CLI_PROFILE);
  const patchFile = path.join(targetDir, 'cordis.patch.yml');

  // Re-running with identical content is a no-op, so `install` stays idempotent
  // and never rewrites a profile the user edited between runs.
  if (!options.force && existsSync(patchFile) && readFileSync(patchFile, 'utf8') === built.text) {
    return { written: false, targetDir, copied: built.copied, missing: built.missing };
  }
  if (built.copied.length === 0) {
    throw new Error('the Desktop profile patch has no capability rows; nothing written');
  }

  mkdirSync(targetDir, { recursive: true });
  writeFileSync(path.join(targetDir, 'package.json'), buildProfileManifest(), 'utf8');
  writeFileSync(patchFile, built.text, 'utf8');
  return { written: true, targetDir, copied: built.copied, missing: built.missing };
}

/**
 * Run the installer.
 *
 * @param {string[]} [argv] Arguments after the script path.
 * @param {{
 *   stdout?: { write(chunk: string): unknown },
 *   stderr?: { write(chunk: string): unknown },
 *   env?: Record<string, string | undefined>,
 * }} [io] Wiring overrides (used by tests).
 * @returns {number} Exit code.
 */
export function main(argv = process.argv.slice(2), io = {}) {
  const stdout = io.stdout ?? process.stdout;
  const stderr = io.stderr ?? process.stderr;
  let options;
  try {
    options = parseOptions(argv, io.env ?? process.env);
  } catch (error) {
    stderr.write(`install-profile: ${error.message}\n`);
    return 2;
  }
  if (options.help) {
    stdout.write(HELP);
    return 0;
  }
  if (!existsSync(options.source)) {
    stderr.write(
      `install-profile: Desktop profile patch not found: ${options.source}\n` +
        'Pass --source <path> or --home <dshHome>.\n',
    );
    return 1;
  }

  const built = buildProfilePatch(readFileSync(options.source, 'utf8'), COPIED_ROWS, {
    provider: options.provider,
    model: options.model,
  });
  const targetDir = path.join(options.home, 'profiles', CLI_PROFILE);

  stdout.write(`source: ${options.source}\n`);
  stdout.write(`target: ${targetDir}\n`);
  stdout.write(`copied: ${built.copied.join(', ') || '(none)'}\n`);
  if (options.provider !== undefined) {
    stdout.write(`route override: ${options.provider}/${options.model}\n`);
  }
  if (built.missing.length > 0) {
    stdout.write(`not found (skipped): ${built.missing.join(', ')}\n`);
  }
  if (built.copied.length === 0) {
    stderr.write('install-profile: the source patch has no capability rows; nothing written\n');
    return 1;
  }
  if (options.dryRun) {
    stdout.write('dry run: no files written\n');
    return 0;
  }

  mkdirSync(targetDir, { recursive: true });
  writeFileSync(path.join(targetDir, 'package.json'), buildProfileManifest(), 'utf8');
  writeFileSync(path.join(targetDir, 'cordis.patch.yml'), built.text, 'utf8');
  stdout.write(
    `installed. Verify with: node "C:\\Program Files\\DSH Desktop\\resources\\app\\node_modules\\@deepseek-ai\\dsh\\lib\\bin.js" --profile ${CLI_PROFILE} --dump-config\n`,
  );
  return 0;
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  process.exitCode = main();
}
