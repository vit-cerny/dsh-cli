test('the plugin table is plain aligned text with a status per row', () => {
  const rows = [
    { id: 'web', name: '@deepseek-ai/dsh-web', enabled: true, source: 'home', bundled: true },
    { id: 'llm-pi-ai', name: '@deepseek-ai/dsh-llm-pi-ai', enabled: true, source: 'desktop', bundled: true },
    { id: 'agent-default-model', name: 'agent-default-model', enabled: true, source: 'dsh-cli', bundled: false },
    { id: 'local-tool', name: 'my-local-tool', enabled: false, source: 'home', bundled: false },
  ];
  const lines = formatPluginTable(rows, {
    missing: [rows[1]],
    disabled: [rows[3]],
  });

  assert.equal(lines[0].startsWith('status'), true);
  assert.match(lines[0], /\bid\b.*\bname\b.*\bsource\b/);
  assert.equal(lines.length, 5);
  assert.match(lines.join('\n'), /missing\s+llm-pi-ai\s+@deepseek-ai\/dsh-llm-pi-ai \(bundled\)\s+desktop/);
  assert.match(lines.join('\n'), /disabled\s+local-tool\s+my-local-tool\s+home/);
  assert.match(lines.join('\n'), /synced\s+web\s+@deepseek-ai\/dsh-web \(bundled\)\s+home/);
  assert.doesNotMatch(lines.join('\n'), /[│┌┐└┘─━╔╗═║]/u);

  // Every data row starts its id at the same column, which is what "aligned" means here.
  const starts = ['agent-default-model', 'llm-pi-ai', 'local-tool', 'web'].map(
    (id, index) => lines[index + 1].indexOf(id),
  );
  assert.equal(new Set(starts).size, 1);
});

test('runPluginsCommand prints the table and a sync summary without writing', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const stdout = capture();
    const before = fixture.read('cli');
    const code = runPluginsCommand(
      { dshHome: fixture.home, profile: 'dsh-cli', provider: 'logfare', model: 'deepseek-v4.1-flash-1017' },
      { stdout, sync: true },
    );

    assert.equal(code, 0);
    assert.match(stdout.text, /status\s+id\s+name\s+source/);
    assert.match(stdout.text, /missing\s+llm-pi-ai/);
    assert.match(stdout.text, /dry run: no files written/);
    assert.match(stdout.text, /run with --apply/);
    assert.equal(fixture.read('cli'), before);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('runPluginsCommand --json carries the rows and the diff', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const stdout = capture();
    assert.equal(
      runPluginsCommand(
        { dshHome: fixture.home, profile: 'dsh-cli', provider: 'p', model: 'm' },
        { stdout, json: true },
      ),
      0,
    );
    const parsed = JSON.parse(stdout.text);
    assert.ok(parsed.rows.some((row) => row.source === 'home'));
    assert.deepEqual(parsed.diff.missing.map((row) => row.id).sort(), ['desktop-shell', 'llm-pi-ai', 'ui-chat']);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('a missing DSH home is an empty inventory, not a crash', () => {
  const root = mkdtempSync(path.join(os.tmpdir(), 'dsh-cli-plugins-'));
  try {
    const home = path.join(root, 'absent');
    assert.deepEqual(readInstalledPlugins(home), []);
    assert.deepEqual(syncPlugins(home, { apply: true }), {
      target: path.join(home, 'profiles', 'dsh-cli', 'cordis.patch.yml'),
      diff: { missing: [], extra: [], disabled: [] },
      copied: [],
      skipped: [],
      written: false,
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});