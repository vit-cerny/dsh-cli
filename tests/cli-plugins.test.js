/**
 * Build a throwaway DSH home; every layer is optional so a test can leave one out.
 *
 * @param {{ desktop?: string, cli?: string, home?: string }} patches Layer contents.
 * @returns {{ root: string, home: string, read: (layer: 'desktop'|'cli'|'home') => string }}
 */
function makeHome(patches) {
  const root = mkdtempSync(path.join(os.tmpdir(), 'dsh-cli-plugins-'));
  const home = path.join(root, 'dsh-home');
  const files = {
    desktop: path.join(home, 'profiles', 'desktop', 'cordis.patch.yml'),
    cli: path.join(home, 'profiles', 'dsh-cli', 'cordis.patch.yml'),
    home: path.join(home, 'cordis.patch.yml'),
  };
  for (const [layer, file] of Object.entries(files)) {
    if (patches[layer] === undefined) continue;
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, patches[layer], 'utf8');
  }
  return { root, home, read: (layer) => readFileSync(files[layer], 'utf8') };
}

function capture() {
  return {
    text: '',
    write(chunk) {
      this.text += String(chunk);
      return true;
    },
  };
}

test('readInstalledPlugins reads every patch layer and marks bundled rows', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const rows = readInstalledPlugins(fixture.home);
    const byLayer = (source) => rows.filter((row) => row.source === source);

    assert.deepEqual(
      byLayer('desktop').map((row) => row.id),
      ['agent-default-model', 'subagent', 'desktop-shell', 'ui-chat', 'web', 'llm-pi-ai'],
    );
    assert.deepEqual(byLayer('dsh-cli').map((row) => row.id), ['agent-default-model', 'subagent']);
    assert.deepEqual(
      byLayer('home').map((row) => row.id),
      ['web', 'mcp-config', 'local-tool'],
    );

    const web = byLayer('desktop').find((row) => row.id === 'web');
    assert.equal(web.name, '@deepseek-ai/dsh-web');
    assert.equal(web.bundled, true);
    assert.equal(byLayer('desktop').find((row) => row.id === 'desktop-shell').bundled, false);
    assert.equal(byLayer('desktop').find((row) => row.id === 'agent-default-model').bundled, false);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('a desktop-only capability row is reported missing from the cli profile', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const rows = readInstalledPlugins(fixture.home);
    const shared = rows.filter((row) => row.source === 'home');
    const diff = diffPlugins(
      [...rows.filter((row) => row.source === 'desktop'), ...shared],
      [...rows.filter((row) => row.source === 'dsh-cli'), ...shared],
    );

    assert.deepEqual(diff.missing.map((row) => row.id).sort(), ['desktop-shell', 'llm-pi-ai', 'ui-chat']);
    assert.ok(diff.missing.every((row) => row.source === 'desktop'));
    assert.deepEqual(diff.extra, []);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('home-layer rows are seen by both profiles, so they are not differences', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const rows = readInstalledPlugins(fixture.home);
    const shared = rows.filter((row) => row.source === 'home');
    assert.ok(shared.some((row) => row.id === 'mcp-config'));

    const sameDiff = diffPlugins(shared, shared);
    assert.deepEqual(sameDiff.missing, []);
    assert.deepEqual(sameDiff.extra, []);
    assert.deepEqual(sameDiff.disabled.map((row) => row.id), ['local-tool']);

    // A home row present in only one list still belongs to both profiles.
    const desktopOnly = [...rows.filter((row) => row.source === 'desktop'), ...shared];
    assert.deepEqual(diffPlugins(desktopOnly, []).missing.map((row) => row.id), [
      'agent-default-model',
      'subagent',
      'desktop-shell',
      'ui-chat',
      'llm-pi-ai',
    ]);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('diffPlugins reports extra rows and rows the cli profile disabled', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const rows = readInstalledPlugins(fixture.home);
    const cli = rows.filter((row) => row.source === 'dsh-cli');
    const diff = diffPlugins(
      rows.filter((row) => row.source === 'desktop'),
      [
        ...cli,
        { id: 'web', name: '@deepseek-ai/dsh-web', enabled: true, source: 'home', bundled: true },
        { id: 'local-tool', name: 'my-local-tool', enabled: false, source: 'home', bundled: false },
        { id: 'cli-only', name: 'cli-only', enabled: true, source: 'dsh-cli', bundled: false },
      ],
    );

    assert.deepEqual(diff.extra.map((row) => row.id), ['cli-only']);
    assert.deepEqual(diff.disabled.map((row) => row.id), ['local-tool']);
    assert.ok(!diff.missing.some((row) => row.id === 'web'));
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('readPluginProfileRows honours the home layer and disabled rows', () => {
  const fixture = makeHome({ cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const enabled = readPluginProfileRows(fixture.home, 'dsh-cli');
    assert.ok(enabled.has('agent-default-model'));
    assert.ok(enabled.has('mcp-config'));
    assert.ok(!enabled.has('local-tool'));
    assert.ok(!enabled.has('web-deepseek-api'));
    assert.deepEqual([...readPluginProfileRows(fixture.home, 'absent')], ['web', 'mcp-config']);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

