test('syncPlugins is a dry run by default and leaves the patch untouched', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const before = fixture.read('cli');
    const result = syncPlugins(fixture.home);

    assert.equal(result.written, false);
    assert.equal(result.copied.includes('llm-pi-ai'), true);
    assert.equal(fixture.read('cli'), before);
    assert.match(result.target, /profiles[\\/]dsh-cli[\\/]cordis\.patch\.yml$/);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

test('syncPlugins writes the missing row once and a second sync does not duplicate it', () => {
  const fixture = makeHome({ desktop: DESKTOP_PATCH, cli: CLI_PATCH, home: HOME_PATCH });
  try {
    const desktopBefore = fixture.read('desktop');
    const first = syncPlugins(fixture.home, { apply: true });

    assert.equal(first.written, true);
    assert.deepEqual(first.copied, ['llm-pi-ai']);
    const written = fixture.read('cli');
    assert.ok(written.includes('apiKeyEnv: LOGFARE_API_KEY'));
    assert.ok(written.startsWith(CLI_PATCH.trimEnd()));
    assert.equal(written.split('- id: llm-pi-ai').length - 1, 1);

    // Only capability rows move: the Electron surface stays on the Desktop side.
    assert.deepEqual(
      first.skipped.map((row) => row.id).sort(),
      ['desktop-shell', 'ui-chat'],
    );
    assert.equal(fixture.read('desktop'), desktopBefore);

    const second = syncPlugins(fixture.home, { apply: true });
    assert.equal(second.written, false);
    assert.deepEqual(second.copied, []);
    assert.equal(fixture.read('cli'), written);
    assert.equal(written.split('- id: llm-pi-ai').length - 1, 1);
  } finally {
    rmSync(fixture.root, { recursive: true, force: true });
  }
});

